var LANG_FLAGS = { de: '🇩🇪', en: '🇬🇧' };

// First start: follow the device language (German or English, else English).
function detectDeviceLang(langs){
  langs = langs || navigator.languages || [navigator.language || ''];
  for (var i = 0; i < langs.length; i++) {
    var code = String(langs[i] || '').slice(0, 2).toLowerCase();
    if (I18N[code]) return code;
  }
  return 'en';
}
if (!I18N[settings.lang]) { settings.lang = detectDeviceLang(); saveSettings(); }

function t(key){
  var d = I18N[settings.lang] || I18N.de;
  return d[key] !== undefined ? d[key] : (I18N.de[key] !== undefined ? I18N.de[key] : key);
}
function tf(key){
  var args = arguments;
  return t(key).replace(/\{(\d+)\}/g, function(m, i){ return args[+i + 1]; });
}
function posName(code){ return code ? t('pos_' + code) : ''; }

function applyStaticTranslations(){
  document.documentElement.lang = settings.lang;
  document.querySelectorAll('[data-i18n]').forEach(function(el){ el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-html]').forEach(function(el){ el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){ el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el){ el.title = t(el.getAttribute('data-i18n-title')); });
  document.getElementById('btnLang').textContent = LANG_FLAGS[settings.lang];
}

function toggleLang(){
  settings.lang = settings.lang === 'de' ? 'en' : 'de';
  saveSettings();
  applyStaticTranslations();
  renderAll();
}
